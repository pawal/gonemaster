import "@testing-library/jest-dom/vitest";

const storage = () => {
  const store = new Map();
  return {
    getItem: (key) => (store.has(key) ? store.get(key) : null),
    setItem: (key, value) => {
      store.set(key, String(value));
    },
    removeItem: (key) => {
      store.delete(key);
    },
    clear: () => {
      store.clear();
    }
  };
};

Object.defineProperty(globalThis, "localStorage", {
  value: storage(),
  configurable: true
});
